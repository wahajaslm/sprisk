"""Merge every contracts/schemas/*.schema.json into one bundle with a shared $defs.

Each source file holds only `$defs`; refs are written as `#/$defs/<Name>` and resolve
inside the bundle. Generators read the bundle, so shared types are defined once.
"""

import json
import sys
from pathlib import Path

SCHEMAS = Path(__file__).parents[1] / "schemas"
BUNDLE = Path(__file__).parents[1] / "bundle.schema.json"


def bundle() -> dict[str, object]:
    defs: dict[str, object] = {}
    owner: dict[str, str] = {}
    for path in sorted(SCHEMAS.glob("*.schema.json")):
        source = json.loads(path.read_text())
        extra = set(source) - {"$schema", "$comment", "$defs"}
        if extra:
            sys.exit(f"{path.name}: only $defs allowed at top level, found {sorted(extra)}")
        for name, schema in source["$defs"].items():
            if name in defs:
                sys.exit(f"{path.name}: $defs/{name} already defined in {owner[name]}")
            defs[name] = schema
            owner[name] = path.name
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "https://sprisk.dev/schemas/bundle.schema.json",
        "$comment": "Generated by contracts/tools/bundle.py. Do not edit.",
        "title": "Bundle",
        "$defs": defs,
    }


if __name__ == "__main__":
    BUNDLE.write_text(json.dumps(bundle(), indent=2, ensure_ascii=False) + "\n")
